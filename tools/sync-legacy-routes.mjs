import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const routes = {
  'anthrocybernetics/index.html': 'projects/anthrocybernetics/index.html',
  'ragdoll-math-lab/index.html': 'projects/ragdoll-math-lab/index.html',
  'round-4/submission/index.html': 'rounds/round-4/submission/index.html',
  'round-5/results/luna/submission/index.html': 'rounds/round-5/results/luna/submission/index.html',
  'round-5/results/terra/submission/index.html': 'rounds/round-5/results/terra/submission/index.html',
  'round-5/results/sol/submission/index.html': 'rounds/round-5/results/sol/submission/index.html'
};

function redirect(target) {
  const url = JSON.stringify(target);
  return `<!doctype html>
<!-- Generated by tools/sync-legacy-routes.mjs. Edit the canonical project. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Demo moved | Public HTML5 Demos</title><link rel="canonical" href="${target}">
<noscript><meta http-equiv="refresh" content="0; url=${target}"></noscript>
<script>location.replace(${url} + location.search + location.hash);</script></head>
<body><p>This demo has moved. <a href="${target}">Open the demo</a>.</p></body></html>
`;
}

const outputs = new Map();
for (const [legacy, canonical] of Object.entries(routes)) {
  const target = path.posix.relative(path.posix.dirname(legacy), canonical);
  outputs.set(legacy, redirect(target));
}
// The existing Sites sync fetches this raw source path. Keep its executable
// export until that downstream allowlist migrates; a redirect would break it.
const ragdoll = await readFile(path.join(root, 'projects/ragdoll-lab/index.html'), 'utf8');
outputs.set('ragdoll-lab/index.html', ragdoll
  .replaceAll('../../assets/', '../assets/')
  .replaceAll('../../shared/', '../shared/'));

for (const [relative, content] of outputs) {
  const destination = path.join(root, relative);
  if (checkOnly) {
    const current = await readFile(destination, 'utf8').catch(() => null);
    if (current !== content) throw new Error(`Stale compatibility route: ${relative}; run node tools/sync-legacy-routes.mjs`);
  } else {
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
console.log(`${checkOnly ? 'Verified' : 'Generated'} ${outputs.size} legacy routes; canonical sources live under projects/ and rounds/.`);
